"""Learn marking ladder: the gate-run harness and its report (main repo
docs/guides/learn-marking-test-protocol.md; spec docs/systems/learn-marking-levels.md,
`learn-marking §N`).

Live and manual — CI never makes a model call here (its tests run it with a stubbed provider).
For each pre-registered answer in tests/fixtures/learn_marking_eval_v1/answers.json it:

  1. builds the request a real Learn client sends: `marking: "ladder-v1"`, the questionId and the
     demandsVersion (and asserts the demands resolve), and the depth and DETERMINISTIC SIGNALS the
     client computes (client_inputs.json, generated by the frontend's `npm run learn:marking-inputs`
     from the real client code, refused if an answer's text no longer matches)
  2. renders the production ladder prompt (main.build_user_prompt) and makes the production call:
     Groq with main._groq_feedback_kwargs, or (Stage 4) Gemini through main.get_gemini_ladder().
     One call at a time, AI_PROVIDER_TIMEOUT_SEC=120, `retry-after` honoured; a daily-limit 429
     stops the run cleanly (exit 3) — run the same command again tomorrow and it resumes
  3. puts the reply through the production pipeline (ladder validation, apply_learn_ladder,
     enrich_feedback, the quality gate, the depth caps)
  4. appends one JSONL record: the raw output, usage, finish_reason, latency, model, every version,
     the request, the scored result, and the commit SHA of answers.json

A record is an observation once the model has answered (status `ok`, or `contract_error` for
invalid JSON or an unusable levelCheck: both count in G11 and are never retried). A transport
failure is recorded as `transport_error` and retried on the next run.

Usage (from backend/, with backend/.env holding GROQ_API_KEY / GEMINI_API_KEY):
    python scripts/learn_marking_eval.py --stage smoke       # Stage 1: 3 calls; stops on invalid
                                                             # JSON, truncation or > 8,000 tokens
    python scripts/learn_marking_eval.py --stage full        # Stage 2: all 22, run 1
    python scripts/learn_marking_eval.py --stage stability   # Stage 3: 8 answers, runs 2 and 3
    python scripts/learn_marking_eval.py --stage gemini      # Stage 4 (optional, not a gate)
    python scripts/learn_marking_eval.py --report [--provider groq] [--report-out report.md]

Smoke-stage records are kept for G11 but never stand in for the full run (Stage 2 calls those three
answers again). Every gate threshold below is UNVALIDATED and pre-registered in the protocol.
"""

