# The protocol fixes the provider timeout for the gate run. The harness's own calls use this constant
# (main reads AI_PROVIDER_TIMEOUT_SEC once, at import, which may already have happened); the env is set
# too, for anything main does with it.
PROVIDER_TIMEOUT_SEC = 120.0
os.environ["AI_PROVIDER_TIMEOUT_SEC"] = str(int(PROVIDER_TIMEOUT_SEC))

FIXTURE_DIR = ROOT / "tests" / "fixtures" / "learn_marking_eval_v1"
ANSWERS_PATH = FIXTURE_DIR / "answers.json"
CLIENT_INPUTS_PATH = FIXTURE_DIR / "client_inputs.json"
DEFAULT_LOG = FIXTURE_DIR / "runs" / "run_log.jsonl"

RECORD_SCHEMA = 1
LEVEL_NAMES = ("A1", "A2", "exam", "B1", "B2")

# Stage 1 stop rules and the G11 cost limits (protocol, "Stages and budget"; G11). UNVALIDATED.
# Raised twice on 2026-10-19 by the owner, from 6,000 / median 5,000:
# - to 7,000 / 6,000 after smoke iteration 0: the ladder prompt alone is ~4,100-4,250 tokens (v6's
#   coaching rules and schema, kept unchanged by design), which the 5,000-per-call estimate missed;
# - max to 8,000 after smoke iteration 1: a 4-error answer used 7,204, and 53% of that reply is v6
#   listing every error twice (grammar + corrections); the ladder's own keys were 9%. The median
#   stays 6,000, so ladder bloat on ordinary answers still fails G11.
SMOKE_MAX_TOKENS = 8000
G11_MEDIAN_TOKENS = 6000
G11_MAX_TOKENS = 8000
# Retry policy for a non-daily 429/503. A retry-after longer than this is treated like the daily limit.
MAX_RETRIES = 4
MAX_RETRY_AFTER_SEC = 900.0
EXIT_STOPPED = 2
EXIT_DAILY_LIMIT = 3


class DailyLimitReached(Exception):
    """The provider's per-day quota is spent: stop cleanly, resume tomorrow."""


class TransientProviderError(Exception):
    def __init__(self, message: str, retry_after: float | None = None):
        super().__init__(message)
        self.retry_after = retry_after


@dataclass
class ProviderReply:
    content: str
    usage: dict[str, int | None]
    finish_reason: str | None
    model: str


ProviderCall = Callable[[str, str], Awaitable[ProviderReply]]


def _main():
    import main  # noqa: PLC0415 — imported late so the env above applies

    return main


# ── Inputs ──────────────────────────────────────────────────────────────────


def load_fixture() -> dict[str, Any]:
    return json.loads(ANSWERS_PATH.read_text(encoding="utf-8"))


def load_client_inputs() -> dict[str, Any]:
    if not CLIENT_INPUTS_PATH.exists():
        raise SystemExit(
            f"{CLIENT_INPUTS_PATH} is missing — run the frontend's `npm run learn:marking-inputs` and commit it."
        )
    return json.loads(CLIENT_INPUTS_PATH.read_text(encoding="utf-8"))


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def fixture_provenance() -> dict[str, Any]:
    """The commit that holds answers.json, and whether the working copy differs from it."""
    rel = str(ANSWERS_PATH.relative_to(ROOT))
    content_sha = _sha256(ANSWERS_PATH.read_text(encoding="utf-8"))
    try:
        commit = subprocess.run(
            ["git", "-C", str(ROOT), "log", "-1", "--format=%H", "--", rel],
            capture_output=True, text=True, check=True,
        ).stdout.strip() or None
        dirty = bool(subprocess.run(
            ["git", "-C", str(ROOT), "status", "--porcelain", "--", rel],
            capture_output=True, text=True, check=True,
        ).stdout.strip())
    except (OSError, subprocess.CalledProcessError):
        commit, dirty = None, True
    return {"fixtureCommit": commit, "fixtureContentSha256": content_sha, "fixtureDirty": dirty}


def check_preconditions(fixture: dict[str, Any], client_inputs: dict[str, Any], provenance: dict[str, Any]) -> None:
    """Refuse to spend tokens on a run that would not count."""
    main = _main()
    if fixture.get("status") != "signed-off":
        raise SystemExit("The test set is not signed off (answers.json status); no tokens are spent before it is.")
    if provenance["fixtureDirty"] or not provenance["fixtureCommit"]:
        raise SystemExit("answers.json has uncommitted changes: commit it first, so the run records the SHA it used.")
    if not main.learn_ladder_enabled():
        raise SystemExit("LEARN_LADDER_ENABLED is off in this environment; the harness tests the ladder scheme.")
    if client_inputs.get("demandsVersion") != main.LEARN_DEMANDS_VERSION:
        raise SystemExit(
            "client_inputs.json was built against a different demands corpus than this backend's "
            f"({client_inputs.get('demandsVersion')} vs {main.LEARN_DEMANDS_VERSION}): regenerate it."
        )


def build_request(answer: dict[str, Any], fixture: dict[str, Any], client_inputs: dict[str, Any]):
    """The FeedbackRequest a Learn client's request becomes, built the way the route builds it."""
    main = _main()
    entry = client_inputs["answers"].get(answer["id"])
    if entry is None:
        raise SystemExit(f"client_inputs.json has no entry for {answer['id']}: regenerate it.")
    if entry["transcriptSha256"] != _sha256(answer["transcript"]):
        raise SystemExit(f"{answer['id']}'s transcript changed since client_inputs.json was built: regenerate it.")
    demands_version = client_inputs["demandsVersion"]
    if main.resolve_learn_demands(answer["questionId"], demands_version) is None:
        raise SystemExit(f"Demands do not resolve for {answer['questionId']} at {demands_version}.")
    marking = main._effective_marking(main._parse_marking("ladder-v1"), has_audio=False)
    assert marking == "ladder-v1"
    req = main.FeedbackRequest(
        question=fixture["questions"][answer["questionId"]]["text"][: main._FEEDBACK_QUESTION_MAX_CHARS],
        transcript=main.clean_transcript(answer["transcript"])[: main._FEEDBACK_TRANSCRIPT_MAX_CHARS],
        model="groq",
        depth=main._normalize_feedback_depth(entry["depth"]),
        question_id=answer["questionId"],
        demands_version=demands_version,
        demand_signals=main.DemandSignals(**entry["demandSignals"]) if entry.get("demandSignals") else None,
        marking=marking,
    )
    return req


# ── Providers ───────────────────────────────────────────────────────────────


def _retry_after(exc: Exception) -> float | None:
    response = getattr(exc, "response", None)
    headers = getattr(response, "headers", None) or {}
    value = headers.get("retry-after") if hasattr(headers, "get") else None
    try:
        return float(value) if value is not None else None
    except (TypeError, ValueError):
        return None


def _is_daily_limit(exc: Exception) -> bool:
    text = str(exc)
    return "per day" in text.lower() or "TPD" in text or "RPD" in text or "PerDay" in text


async def call_groq(prompt: str, depth: str) -> ProviderReply:
    main = _main()
    groq = main.get_groq()
    if not groq:
        raise SystemExit("GROQ_API_KEY is not set.")
    try:
        resp = await asyncio.wait_for(
            groq.chat.completions.create(**main._groq_feedback_kwargs(prompt, depth, ladder=True)),
            timeout=PROVIDER_TIMEOUT_SEC,
        )
    except asyncio.TimeoutError as exc:
        raise TransientProviderError("timeout") from exc
    except Exception as exc:  # noqa: BLE001 — classified below
        if _is_daily_limit(exc):
            raise DailyLimitReached(str(exc)) from exc
        if main._is_retryable(exc):
            raise TransientProviderError(str(exc), _retry_after(exc)) from exc
        raise
    choice = resp.choices[0]
    usage = getattr(resp, "usage", None)
    return ProviderReply(
        content=choice.message.content or "",
        usage={
            "promptTokens": getattr(usage, "prompt_tokens", None),
            "completionTokens": getattr(usage, "completion_tokens", None),
            "totalTokens": getattr(usage, "total_tokens", None),
        },
        finish_reason=getattr(choice, "finish_reason", None),
        model=f"groq/{getattr(resp, 'model', None) or main.GROQ_MODEL}",
    )


async def call_gemini(prompt: str, depth: str) -> ProviderReply:
    main = _main()
    gemini = main.get_gemini_ladder()
    if not gemini:
        raise SystemExit("GEMINI_API_KEY is not set.")
    try:
        resp = await asyncio.wait_for(asyncio.to_thread(gemini.generate_content, prompt), timeout=PROVIDER_TIMEOUT_SEC)
    except asyncio.TimeoutError as exc:
        raise TransientProviderError("timeout") from exc
    except Exception as exc:  # noqa: BLE001
        if main._is_daily_quota_exhausted(exc):
            raise DailyLimitReached(str(exc)) from exc
        if main._is_retryable(exc):
            raise TransientProviderError(str(exc), _retry_after(exc)) from exc
        raise
    meta = getattr(resp, "usage_metadata", None)
    candidates = getattr(resp, "candidates", None) or []
    finish = getattr(candidates[0], "finish_reason", None) if candidates else None
    return ProviderReply(
        content=getattr(resp, "text", "") or "",
        usage={
            "promptTokens": getattr(meta, "prompt_token_count", None),
            "completionTokens": getattr(meta, "candidates_token_count", None),
            "totalTokens": getattr(meta, "total_token_count", None),
        },
        finish_reason=getattr(finish, "name", None) or (str(finish) if finish is not None else None),
        model=f"gemini/{main.GEMINI_MODEL}",
    )


PROVIDERS: dict[str, ProviderCall] = {"groq": call_groq, "gemini": call_gemini}


def is_truncated(finish_reason: str | None) -> bool:
    return (finish_reason or "").lower() in ("length", "max_tokens")


# ── One call ────────────────────────────────────────────────────────────────


def process_reply(req, reply_content: str) -> tuple[str, str | None, dict[str, Any] | None, dict[str, Any] | None]:
    """(status, error, rawLevelCheck, result) through the production pipeline."""
    main = _main()
    ll = main._learn_ladder
    try:
        raw = main.extract_json(reply_content)
    except (ValueError, json.JSONDecodeError) as exc:
        return "contract_error", f"invalid_json: {exc}", None, None
    raw_level_check = raw.get("levelCheck") if isinstance(raw, dict) else None
    applies = ll.applicable_ladders(main.resolve_learn_demands(req.question_id, req.demands_version))
    try:
        ll.validate_raw_levelcheck(raw_level_check, applies)
    except ll.LadderValidationError as exc:
        return "contract_error", f"invalid_levelcheck: {exc}", raw_level_check, None
    fb = copy.deepcopy(raw)
    fb.setdefault("providerStatus", "primary")
    result = main.enrich_feedback(main.apply_learn_ladder(fb, req), req)
    result = main._apply_coaching_quality_gate(result, req.transcript)
    result = main._apply_depth_item_caps(result, req.depth)
    return "ok", None, raw_level_check, result


async def run_one(
    answer: dict[str, Any], run: int, stage: str, provider: str, fixture, client_inputs, provenance,
    call: ProviderCall, sleep: Callable[[float], Awaitable[None]] = asyncio.sleep,
) -> dict[str, Any]:
    main = _main()
    req = build_request(answer, fixture, client_inputs)
    prompt = main.build_user_prompt(req)
    record: dict[str, Any] = {
        "schema": RECORD_SCHEMA,
        "fixture": fixture["fixture"],
        **provenance,
        "clientInputsSha256": _sha256(CLIENT_INPUTS_PATH.read_text(encoding="utf-8")),
        "answerId": answer["id"],
        "questionId": answer["questionId"],
        "type": answer["type"],
        "run": run,
        "stage": stage,
        "provider": provider,
        "versions": {
            "learnPrompt": main.LEARN_LADDER_PROMPT_VERSION,
            "ladder": main._learn_ladder.LEARN_LADDER_VERSION,
            "demands": req.demands_version,
            "systemPromptSha256": _sha256(main.SYSTEM_PROMPT_LADDER),
            "userPromptSha256": _sha256(prompt),
        },
        "request": {
            "question": req.question,
            "transcript": req.transcript,
            "questionId": req.question_id,
            "demandsVersion": req.demands_version,
            "marking": req.marking,
            "depth": req.depth,
            "demandSignals": req.demand_signals.model_dump(exclude_none=True) if req.demand_signals else None,
        },
        "startedAt": datetime.now(timezone.utc).isoformat(),
    }
    attempt = 0
    while True:
        t0 = time.monotonic()
        try:
            reply = await call(prompt, req.depth)
            break
        except TransientProviderError as exc:
            attempt += 1
            wait = exc.retry_after if exc.retry_after is not None else min(2.0 ** attempt, 30.0)
            if wait > MAX_RETRY_AFTER_SEC:
                raise DailyLimitReached(f"retry-after {wait:.0f}s: {exc}") from exc
            if attempt > MAX_RETRIES:
                record.update(status="transport_error", error=str(exc), latencyMs=None)
                return record
            print(f"  {answer['id']} run {run}: {exc} — waiting {wait:.1f}s (retry {attempt}/{MAX_RETRIES})", file=sys.stderr)
            await sleep(wait)
    latency_ms = int((time.monotonic() - t0) * 1000)
    status, error, raw_level_check, result = process_reply(req, reply.content)
    record.update(
        status=status,
        error=error,
        model=reply.model,
        latencyMs=latency_ms,
        usage=reply.usage,
        finishReason=reply.finish_reason,
        truncated=is_truncated(reply.finish_reason),
        rawOutput=reply.content,
        rawLevelCheck=raw_level_check,
        result=result,
    )
    return record


# ── The log ─────────────────────────────────────────────────────────────────


def read_log(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    records = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            records.append(json.loads(line))
    return records


def append_record(path: Path, record: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(record, ensure_ascii=False) + "\n")


def observed(record: dict[str, Any]) -> bool:
    return record.get("status") in ("ok", "contract_error")


def stage_plan(stage: str, fixture: dict[str, Any]) -> tuple[str, list[tuple[str, int]]]:
    """(provider, [(answerId, run)]) for a stage."""
    all_ids = [a["id"] for a in fixture["answers"]]
    if stage == "smoke":
        return "groq", [(i, 1) for i in fixture["stages"]["smoke"]["answers"]]
    if stage == "full":
        return "groq", [(i, 1) for i in all_ids]
    if stage == "stability":
        extra = fixture["stages"]["stability"]["extraRuns"]
        return "groq", [(i, run) for run in range(2, 2 + extra) for i in fixture["stages"]["stability"]["answers"]]
    if stage == "gemini":
        return "gemini", [(i, 1) for i in all_ids]
    raise SystemExit(f"Unknown stage {stage!r}")


def current_versions() -> dict[str, str]:
    main = _main()
    return {
        "learnPrompt": main.LEARN_LADDER_PROMPT_VERSION,
        "ladder": main._learn_ladder.LEARN_LADDER_VERSION,
        "systemPromptSha256": _sha256(main.SYSTEM_PROMPT_LADDER),
    }


def check_log_matches_prompt(records: list[dict[str, Any]]) -> None:
    """One log, one prompt: records from another prompt or ladder version would mix two judges in one
    report and make resume skip answers the new prompt never saw."""
    want = current_versions()
    for record in records:
        got = {k: (record.get("versions") or {}).get(k) for k in want}
        if got != want:
            raise SystemExit(
                f"The log holds records from another prompt or ladder version ({got} vs {want}). "
                "Move it aside (keep it as evidence) and start a new log."
            )


def smoke_stop_reason(record: dict[str, Any]) -> str | None:
    if record["status"] == "contract_error" and (record.get("error") or "").startswith("invalid_json"):
        return "invalid JSON"
    if record.get("truncated"):
        return f"truncated (finish_reason {record.get('finishReason')})"
    total = (record.get("usage") or {}).get("totalTokens")
    if total is not None and total > SMOKE_MAX_TOKENS:
        return f"{total} tokens > {SMOKE_MAX_TOKENS}"
    return None


async def run_stage(
    stage: str, log_path: Path, *, providers: dict[str, ProviderCall] | None = None,
    sleep: Callable[[float], Awaitable[None]] = asyncio.sleep, check: bool = True,
) -> int:
    fixture = load_fixture()
    client_inputs = load_client_inputs()
    provenance = fixture_provenance()
    if check:
        check_preconditions(fixture, client_inputs, provenance)
    provider, plan = stage_plan(stage, fixture)
    call = (providers or PROVIDERS)[provider]
    answers = {a["id"]: a for a in fixture["answers"]}
    existing = read_log(log_path)
    check_log_matches_prompt(existing)
    done = {(r["provider"], r["stage"], r["answerId"], r["run"]) for r in existing if observed(r)}
    todo = [(i, run) for i, run in plan if (provider, stage, i, run) not in done]
    print(f"Stage {stage} ({provider}): {len(plan) - len(todo)} of {len(plan)} already observed, {len(todo)} to call.")
    for answer_id, run in todo:  # one call at a time
        try:
            record = await run_one(answers[answer_id], run, stage, provider, fixture, client_inputs, provenance, call, sleep)
        except DailyLimitReached as exc:
            print(f"Daily limit reached at {answer_id} run {run}: {exc}\nRun the same command again tomorrow to resume.")
            return EXIT_DAILY_LIMIT
        append_record(log_path, record)
        tokens = (record.get("usage") or {}).get("totalTokens")
        print(f"  {answer_id} run {run}: {record['status']}{' — ' + record['error'] if record.get('error') else ''}"
              f" ({tokens} tokens, {record.get('latencyMs')} ms)")
        if stage == "smoke":
            reason = smoke_stop_reason(record)
            if reason:
                print(f"STOP (Stage 1 rule): {answer_id}: {reason}. Fix this before Stage 2.")
                return EXIT_STOPPED
    return 0


# ── The report (protocol, "Pass gates") ─────────────────────────────────────


def overalls(record: dict[str, Any]) -> dict[str, float]:
    ll = _main()._learn_ladder
    by_level = record["result"]["levelCheck"]["subScoresByLevel"]
    return {level: ll.overall_from_sub_scores(by_level[level]) for level in LEVEL_NAMES}


def model_verdicts(record: dict[str, Any], ladder: str) -> list[str | None]:
    """The model's own verdicts (before the quote guardrail), with the spec's reading: a null counts as
    "n" except on the A1 rung of O and F, which has no requirement."""
    raw = (record.get("rawLevelCheck") or {}).get(ladder) or {}
    verdicts = list(raw.get("verdicts") or [None] * 4)
    out: list[str | None] = []
    for index, verdict in enumerate(verdicts):
        if index == 0 and ladder in ("O", "F"):
            out.append(None)
        else:
            out.append("y" if verdict == "y" else "n")
    return out


def reported_error_quotes(record: dict[str, Any]) -> list[str]:
    result = record.get("result") or {}
    quotes = []
    for bucket in ("critical", "polish"):
        for item in (result.get("grammar") or {}).get(bucket) or []:
            if isinstance(item, dict) and item.get("quote"):
                quotes.append(item["quote"])
    for item in result.get("corrections") or []:
        if isinstance(item, dict) and item.get("quote"):
            quotes.append(item["quote"])
    return quotes


def _matches(seeded_quote: str, reported: list[str]) -> bool:
    norm = _main()._learn_ladder._normalise
    target = norm(seeded_quote)
    for quote in reported:
        other = norm(quote)
        if other and (target in other or other in target):
            return True
    return False


def _gate(rows: list, number: str, name: str, threshold: str, passed: bool | None, detail: str) -> None:
    status = "OWNER" if passed is None else ("PASS" if passed else "FAIL")
    rows.append((number, name, threshold, status, detail))


def _fmt(x: float) -> str:
    return f"{x:.1f}"


def build_report(records: list[dict[str, Any]], provider: str = "groq") -> tuple[str, bool]:
    """(markdown, every automatic gate passed). G13 is the owner's read and is printed, not judged."""
    fixture = load_fixture()
    main = _main()
    ll = main._learn_ladder
    answers = {a["id"]: a for a in fixture["answers"]}
    mine = [r for r in records if r.get("provider") == provider]
    # The latest observation per (stage, answer, run); smoke records count for G11 only.
    latest: dict[tuple[str, str, int], dict[str, Any]] = {}
    for record in mine:
        if observed(record):
            latest[(record["stage"], record["answerId"], record["run"])] = record
    calls = list(latest.values())
    gate_calls = [r for r in calls if r["stage"] != "smoke"]
    ok = [r for r in gate_calls if r["status"] == "ok"]
    run1 = {r["answerId"]: r for r in ok if r["run"] == 1}
    by_type: dict[str, list[str]] = {}
    for answer in fixture["answers"]:
        by_type.setdefault(answer["type"], []).append(answer["id"])

    rows: list = []
    lines = [f"# Learn marking gate report — {provider}", ""]
    # Per-run versions only; userPromptSha256 differs per answer by design.
    versions = sorted({
        json.dumps({k: v for k, v in r.get("versions", {}).items() if k != "userPromptSha256"}, sort_keys=True)
        for r in calls
    })
    commits = sorted({r.get("fixtureCommit") or "?" for r in calls})
    models = sorted({r.get("model") or "?" for r in calls})
    lines += [
        f"- Observed calls: {len(calls)} ({len(gate_calls)} gate-stage, {len(calls) - len(gate_calls)} smoke)",
        f"- Run 1 scored: {len(run1)} of {len(answers)} answers",
        f"- answers.json commit(s): {', '.join(commits)}",
        f"- Model(s): {', '.join(models)}",
        f"- Versions: {'; '.join(versions) or '—'}",
        "",
    ]
    missing = [i for i in answers if i not in run1]

    def need_all(ids):
        return all(i in run1 for i in ids)

    def scored(ids):
        return f"{sum(i in run1 for i in ids)}/{len(ids)} scored, none outside the threshold"

    # G1 — order, every scored answer-run.
    bad = [f"{r['answerId']}#{r['run']}" for r in ok
           if not all(a >= b for a, b in zip(list(overalls(r).values()), list(overalls(r).values())[1:]))]
    _gate(rows, "G1", "Order A1 ≥ A2 ≥ Exam ≥ B1 ≥ B2", "100% of answer-runs", bool(ok) and not bad,
          f"{len(ok) - len(bad)}/{len(ok)}" + (f"; out of order: {', '.join(bad)}" if bad else ""))

    # G2 — simple A1.
    ids = by_type["simple_a1"]
    fails = []
    for i in ids:
        if i in run1:
            o = overalls(run1[i])
            if not (o["A1"] >= 8.0 and o["A1"] - o["B1"] >= 3.0 and o["A1"] - o["B2"] >= 4.5):
                fails.append(f"{i} A1 {_fmt(o['A1'])} B1 {_fmt(o['B1'])} B2 {_fmt(o['B2'])}")
    _gate(rows, "G2", "Big gap for simple answers", "A1 ≥ 8.0, A1−B1 ≥ 3.0, A1−B2 ≥ 4.5", need_all(ids) and not fails,
          "; ".join(fails) or scored(ids))

    # G3 — strong B1.
    ids = by_type["strong_b1"]
    fails = [f"{i} A2 {_fmt(overalls(run1[i])['A2'])} B1 {_fmt(overalls(run1[i])['B1'])}" for i in ids
             if i in run1 and not (overalls(run1[i])["A2"] >= 9.0 and overalls(run1[i])["B1"] >= 7.5)]
    _gate(rows, "G3", "Top of scale used", "strong B1: A2 ≥ 9.0, B1 ≥ 7.5", need_all(ids) and not fails,
          "; ".join(fails) or scored(ids))

    # G4 — typical A2.
    ids = by_type["typical_a2"]
    fails = [f"{i} A2 {_fmt(overalls(run1[i])['A2'])} B1 {_fmt(overalls(run1[i])['B1'])}" for i in ids
             if i in run1 and not (overalls(run1[i])["A2"] >= 7.5 and overalls(run1[i])["B1"] <= overalls(run1[i])["A2"] - 2.0)]
    _gate(rows, "G4", "Typical A2 sits at A2", "A2 ≥ 7.5, B1 ≤ A2 − 2.0", need_all(ids) and not fails,
          "; ".join(fails) or scored(ids))

    # G5 — Exam really in between.
    a2_ids, b1_ids = by_type["typical_a2"], by_type["strong_b1"]
    a2_hits = sum(1 for i in a2_ids if i in run1 and overalls(run1[i])["A2"] - overalls(run1[i])["exam"] >= 0.5 - 1e-9)
    b1_hits = sum(1 for i in b1_ids if i in run1 and overalls(run1[i])["exam"] - overalls(run1[i])["B1"] >= 0.5 - 1e-9)
    _gate(rows, "G5", "Exam really in between", "A2−Exam ≥ 0.5 for ≥ 4/5 typical; Exam−B1 ≥ 0.5 for ≥ 4/5 strong",
          need_all(a2_ids + b1_ids) and a2_hits >= 4 and b1_hits >= 4, f"typical {a2_hits}/5, strong {b1_hits}/5")

    # G6 — mistakes count at Exam; seeded-error recall; sound-alike slips.
    ids = by_type["weak"]
    exam_fails = [f"{i} Exam {_fmt(overalls(run1[i])['exam'])}" for i in ids if i in run1 and overalls(run1[i])["exam"] > 6.5]
    seeded = found = 0
    slip_fails = []
    for i in ids:
        if i not in run1:
            continue
        reported = reported_error_quotes(run1[i])
        for error in answers[i]["seededErrors"]:
            seeded += 1
            found += _matches(error["quote"], reported)
    for i, answer in answers.items():
        if not answer["soundAlikeSlips"] or i not in run1:
            continue
        reported = reported_error_quotes(run1[i])
        expected_a = ll.reached_rung(answer["ladders"]["A"]["verdicts"])
        actual_a = ll.LEVELS.index(run1[i]["result"]["levelCheck"]["reached"]["A"]) + 1 \
            if run1[i]["result"]["levelCheck"]["reached"]["A"] != "none" else 0
        for slip in answer["soundAlikeSlips"]:
            if _matches(slip["quote"], reported) and actual_a < expected_a:
                slip_fails.append(f"{i}: « {slip['quote']} » reported and A reached {ll.reached_name(actual_a)} < expected")
    recall = found / seeded if seeded else 0.0
    _gate(rows, "G6", "Mistakes count at Exam", "weak Exam ≤ 6.5; recall ≥ 80%; no slip-only Accuracy failure",
          need_all(ids) and not exam_fails and recall >= 0.8 and not slip_fails,
          "; ".join(exam_fails + slip_fails + [f"recall {found}/{seeded} ({recall:.0%})"]))

    # G7 — off-topic.
    ids = by_type["control_off_topic"]
    fails = [f"{i} {level} {_fmt(v)}" for i in ids if i in run1 for level, v in overalls(run1[i]).items() if v > 2.0]
    _gate(rows, "G7", "Off-topic", "≤ 2.0 at every level", need_all(ids) and not fails, "; ".join(fails) or "all ≤ 2.0")

    # G8 — verdicts match expectations (run 1, the model's own verdicts).
    total = agree = d_total = d_agree = 0
    per_ladder: dict[str, list[int]] = {}
    # Every answer counts. One without a scored run 1 (a contract error) counts every expected verdict
    # as a disagreement — the strictest reading; the protocol does not say how to treat it.
    for i, answer in answers.items():
        record = run1.get(i)
        deciding = {(ladder, level) for ladder, level in answer["decidingRungs"]}
        for ladder, expected in answer["ladders"].items():
            got = model_verdicts(record, ladder) if record else [None] * 4
            for index, want in enumerate(expected["verdicts"]):
                if want is None:
                    continue
                hit = int(got[index] == want)
                total += 1
                agree += hit
                per_ladder.setdefault(ladder, [0, 0])
                per_ladder[ladder][0] += hit
                per_ladder[ladder][1] += 1
                if (ladder, ll.LEVELS[index]) in deciding:
                    d_total += 1
                    d_agree += hit
    ladder_rates = {k: v[0] / v[1] for k, v in per_ladder.items()}
    overall_rate = agree / total if total else 0.0
    deciding_rate = d_agree / d_total if d_total else 0.0
    _gate(rows, "G8", "Verdicts match expectations", "≥ 85% all; ≥ 90% deciding; every ladder ≥ 75%",
          bool(run1) and overall_rate >= 0.85 and deciding_rate >= 0.90 and all(v >= 0.75 for v in ladder_rates.values()),
          (f"unscored, counted as all wrong: {', '.join(missing)}; " if missing else "")
          + f"all {agree}/{total} ({overall_rate:.0%}), deciding {d_agree}/{d_total} ({deciding_rate:.0%}), "
          + ", ".join(f"{k} {v:.0%}" for k, v in sorted(ladder_rates.items())))

    # G9 — stability over 3 runs.
    stab_ids = fixture["stages"]["stability"]["answers"]
    runs_needed = 1 + fixture["stages"]["stability"]["extraRuns"]
    rungs = flips = 0
    spreads: list[float] = []
    spread_fails = []
    complete = True
    for i in stab_ids:
        trio = [r for r in ok if r["answerId"] == i]
        if len({r["run"] for r in trio}) < runs_needed:
            complete = False
            continue
        for ladder, expected in answers[i]["ladders"].items():
            per_run = [model_verdicts(r, ladder) for r in trio]
            for index, want in enumerate(expected["verdicts"]):
                if want is None:
                    continue
                rungs += 1
                flips += int(len({v[index] for v in per_run}) > 1)
        for level in LEVEL_NAMES:
            values = [overalls(r)[level] for r in trio]
            spread = max(values) - min(values)
            spreads.append(spread)
            if spread > 1.0 + 1e-9:
                spread_fails.append(f"{i} {level} {spread:.1f}")
    flip_rate = flips / rungs if rungs else 0.0
    mean_spread = statistics.mean(spreads) if spreads else 0.0
    _gate(rows, "G9", "Stability (3 runs)", "flip ≤ 10%; spread ≤ 1.0 each; mean ≤ 0.5",
          complete and flip_rate <= 0.10 and not spread_fails and mean_spread <= 0.5 + 1e-9,
          ("incomplete — run Stage 3; " if not complete else "")
          + f"flips {flips}/{rungs} ({flip_rate:.0%}), mean spread {mean_spread:.2f}"
          + (f"; over 1.0: {', '.join(spread_fails)}" if spread_fails else ""))

    # G10 — evidence is real (every observed call, before the guardrail).
    quotes = real = 0
    for record in gate_calls:
        transcript = record["request"]["transcript"]
        for ladder, entry in (record.get("rawLevelCheck") or {}).items():
            if isinstance(entry, dict) and "y" in (entry.get("verdicts") or []):
                quotes += 1
                real += ll.quote_in_transcript(entry.get("quote"), transcript)
    evidence_rate = real / quotes if quotes else 0.0
    _gate(rows, "G10", "Evidence is real", "≥ 95% of \"y\" quotes in the transcript", quotes > 0 and evidence_rate >= 0.95,
          f"{real}/{quotes} ({evidence_rate:.0%})")

    # G11 — contract and cost (every observed call, smoke included).
    valid = sum(1 for r in calls if r["status"] == "ok")
    with_demand_check = sum(1 for r in calls if r["status"] == "ok" and r["result"].get("demandCheck") is not None)
    truncations = [f"{r['answerId']}#{r['run']}" for r in calls if r.get("truncated")]
    tokens = [r["usage"]["totalTokens"] for r in calls if (r.get("usage") or {}).get("totalTokens") is not None]
    median_tokens = statistics.median(tokens) if tokens else 0
    max_tokens = max(tokens) if tokens else 0
    valid_rate = valid / len(calls) if calls else 0.0
    _gate(rows, "G11", "Contract and cost", f"≥ 97.5% valid; demandCheck 100%; 0 truncations; median ≤ {G11_MEDIAN_TOKENS:,}, max ≤ {G11_MAX_TOKENS:,}",
          bool(calls) and valid_rate >= 0.975 and with_demand_check == valid and not truncations
          and len(tokens) == len(calls) and median_tokens <= G11_MEDIAN_TOKENS and max_tokens <= G11_MAX_TOKENS,
          f"valid {valid}/{len(calls)} ({valid_rate:.1%}), demandCheck {with_demand_check}/{valid}, "
          f"truncated {len(truncations)}{' (' + ', '.join(truncations) + ')' if truncations else ''}, "
          f"tokens median {median_tokens:.0f} max {max_tokens} ({len(tokens)} with usage)")

    # G12 — needs list.
    ids = by_type["simple_a1"]
    fails = []
    for i in ids:
        if i in run1:
            needs = run1[i]["result"]["levelCheck"]["needsByLevel"]
            if needs["A1"] or len(needs["B1"]) < 2:
                fails.append(f"{i}: A1 {len(needs['A1'])}, B1 {len(needs['B1'])}")
    stray = [f"{r['answerId']}#{r['run']} {item['ladder']}" for r in ok for level, items in
             r["result"]["levelCheck"]["needsByLevel"].items() for item in items
             if item["ladder"] not in r["result"]["levelCheck"]["applies"]]
    _gate(rows, "G12", "Needs list", "simple A1: 0 at A1, ≥ 2 at B1; never a non-applicable ladder",
          need_all(ids) and not fails and not stray, "; ".join(fails + stray) or scored(ids))

    # G13 — the owner's read-through (printed below).
    _gate(rows, "G13", "Owner read-through", "yes for ≥ 4/5 simple-A1 'needs for B1' lists", None,
          "see 'For the owner' below")

    # G14 — only what the question asks.
    target = "hol_01_strong_b1"
    g14_detail = []
    g14_ok = not stray
    if target in run1:
        reached = run1[target]["result"]["levelCheck"]["reached"]
        short = [f"{k} {v}" for k, v in reached.items() if v in ("none", "A1", "A2")]
        g14_ok = g14_ok and not short
        g14_detail.append(f"{target}: " + (", ".join(short) + " below B1" if short else "B1+ on every ladder"))
    else:
        g14_ok = False
        g14_detail.append(f"{target} not scored")
    _gate(rows, "G14", "Only what the question asks", "no stray needs item (unit-proven); hol_01 strong B1 ≥ B1 everywhere",
          g14_ok, "; ".join(g14_detail))

    lines += ["| # | Gate | Threshold | Result | Detail |", "|---|---|---|---|---|"]
    lines += [f"| {n} | {name} | {threshold} | **{status}** | {detail} |" for n, name, threshold, status, detail in rows]
    automatic = [status for _, _, _, status, _ in rows if status != "OWNER"]
    all_pass = all(status == "PASS" for status in automatic)
    lines += ["", f"**Automatic gates: {'ALL PASS' if all_pass else 'NOT PASSED'}** (G13 is the owner's).", ""]
    if missing:
        lines += [f"Run 1 missing for: {', '.join(missing)}", ""]

    lines += ["## Scores, run 1 (overall per level)", "", "| Answer | A1 | A2 | Exam | B1 | B2 | Reached |", "|---|---|---|---|---|---|---|"]
    for i in answers:
        if i in run1:
            o = overalls(run1[i])
            reached = " ".join(f"{k}:{v}" for k, v in run1[i]["result"]["levelCheck"]["reached"].items())
            lines.append(f"| {i} | " + " | ".join(_fmt(o[level]) for level in LEVEL_NAMES) + f" | {reached} |")
        else:
            lines.append(f"| {i} | — | — | — | — | — | not scored |")

    lines += ["", "## For the owner (G13): what each simple answer needs for B1", ""]
    for i in by_type["simple_a1"]:
        lines.append(f"**{i}** — « {answers[i]['transcript']} »")
        if i in run1:
            for item in run1[i]["result"]["levelCheck"]["needsByLevel"]["B1"]:
                step = " (first step)" if item["firstStep"] else ""
                example = f" — e.g. « {item['example']} »" if item.get("example") else ""
                lines.append(f"- {item['label']}{step}: {item['text']}{example}")
        else:
            lines.append("- not scored")
        lines.append("")
    return "\n".join(lines), all_pass


# ── CLI ─────────────────────────────────────────────────────────────────────


def main_cli(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--stage", choices=["smoke", "full", "stability", "gemini"])
    parser.add_argument("--report", action="store_true", help="print the gate table from the log")
    parser.add_argument("--provider", default="groq", choices=sorted(PROVIDERS), help="whose records --report reads")
    parser.add_argument("--log", type=Path, default=DEFAULT_LOG)
    parser.add_argument("--report-out", type=Path, help="also write the report to this file")
    args = parser.parse_args(argv)
    if not args.stage and not args.report:
        parser.error("give --stage or --report")
    code = 0
    if args.stage:
        try:
            from dotenv import load_dotenv  # noqa: PLC0415

            load_dotenv(ROOT / ".env")
        except ImportError:
            pass
        code = asyncio.run(run_stage(args.stage, args.log))
    if args.report:
        text, _ = build_report(read_log(args.log), args.provider)
        print(text)
        if args.report_out:
            args.report_out.write_text(text + "\n", encoding="utf-8")
    return code


if __name__ == "__main__":
    sys.exit(main_cli())
